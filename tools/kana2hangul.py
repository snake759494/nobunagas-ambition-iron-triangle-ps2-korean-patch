"""일본어 가나 읽기 -> 한글 표기 (국립국어원 일본어 표기법 기준, 인명·지명용).

- 어두의 청음 か·た 행은 ㄱ·ㄷ(가/다), 어중·어말은 ㅋ·ㅌ(카/타)
- つ=쓰, ちゃ=차 (어두 자) , 촉음 っ=ㅅ 받침, ん=ㄴ 받침
- 장음은 적지 않는다(おお·うう·おう·えい 의 뒤 모음 생략)
단어 경계(성/이름)마다 따로 변환해야 어두 규칙이 맞는다.
"""
